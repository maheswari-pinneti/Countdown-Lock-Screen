export function getCanvasDimensions(aspectRatio) {
  switch (aspectRatio) {
    case '9:19.5':
      return { width: 1080, height: 2340 };
    case '9:20':
      return { width: 1080, height: 2400 };
    case '9:16':
    default:
      return { width: 1080, height: 1920 };
  }
}
